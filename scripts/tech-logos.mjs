// -----------------------------------------------------------------------------
// Writes components/icons/tech-logos.ts: the brand marks of the tools /uses and
// /about name, read from a Simple Icons package (https://simpleicons.org) as
// data only (its SVG files and data/simple-icons.json; none of its code runs).
//
//   npm pack simple-icons && tar -xzf simple-icons-*.tgz   (in an empty folder)
//   node scripts/tech-logos.mjs <that folder>/package
//
// A tool with no mark here keeps its monogram tile (components/misc/tool-card.tsx).
// -----------------------------------------------------------------------------

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** The site's name for a tool → its Simple Icons slug. */
const TOOLS = {
  Python: "python",
  TypeScript: "typescript",
  FastAPI: "fastapi",
  "Next.js": "nextdotjs",
  React: "react",
  "React Native": "react",
  Django: "django",
  "Tailwind CSS": "tailwindcss",
  LangGraph: "langgraph",
  Gemini: "googlegemini",
  "scikit-learn": "scikitlearn",
  PostgreSQL: "postgresql",
  Neon: "neon",
  Redis: "redis",
  TimescaleDB: "timescale",
  SQLAlchemy: "sqlalchemy",
  Docker: "docker",
  Vercel: "vercel",
  "Hugging Face Spaces": "huggingface",
  "GitHub Actions": "githubactions",
  pytest: "pytest",
  ruff: "ruff",
  "C# / .NET": "dotnet",
};

const root = process.argv[2];
if (!root) throw new Error("usage: node scripts/tech-logos.mjs <simple-icons package folder>");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const data = JSON.parse(readFileSync(join(root, "data", "simple-icons.json"), "utf8"));
const entries = Array.isArray(data) ? data : data.icons;

const lines = Object.entries(TOOLS).map(([name, slug]) => {
  const svg = readFileSync(join(root, "icons", `${slug}.svg`), "utf8");
  const title = /<title>([^<]+)<\/title>/.exec(svg)?.[1];
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  const entry = entries.find((icon) => icon.slug === slug || icon.title === title);
  if (!title || !path || !entry) throw new Error(`${name}: no icon data for "${slug}"`);
  const license = entry.license ? (entry.license.type ?? entry.license.url ?? "custom") : null;
  const notes = [entry.guidelines ? `guidelines: ${entry.guidelines}` : null, license ? `license: ${license}` : null].filter(Boolean);
  return `  ${JSON.stringify(name)}: { title: ${JSON.stringify(title)}, hex: "${entry.hex}", path: ${JSON.stringify(path)} },${notes.length ? ` // ${notes.join("; ")}` : ""}`;
});

writeFileSync(
  "components/icons/tech-logos.ts",
  `// Generated by scripts/tech-logos.mjs from Simple Icons ${version} (CC0 1.0, https://simpleicons.org).
// The marks belong to their owners; the site shows each only to name the tool
// beside it, at small size, in its own colour or in grey. Do not edit by hand.

/** A tool's brand mark: its name in Simple Icons, its brand colour and its SVG path (viewBox 0 0 24 24). */
export type TechLogo = { title: string; hex: string; path: string };

/** By the site's name for the tool (content/site.ts \`uses.groups\`, content/pages/about.ts \`stack\`). */
export const TECH_LOGOS: Readonly<Record<string, TechLogo>> = {
${lines.join("\n")}
};
`,
);
console.log(`wrote ${lines.length} marks from Simple Icons ${version}`);
